import type { Metadata } from "next";
import { ExternalLink, ShieldCheck, Sparkles } from "lucide-react";
import { CopyButton } from "@/components/app/copy-button";
import { MembershipCard } from "@/components/membership-card";
import { PageHeader } from "@/components/app/page-header";
import { ChainBadge } from "@/components/chain-badge";
import { requireRole } from "@/lib/auth";
import { getMemberChainState, getMembershipMetadata } from "@/lib/chain/read";
import { readDb } from "@/lib/db";
import { formatNumber, shortAddress } from "@/lib/format";
import { TIERS, getTier, tierProgress } from "@/lib/membership";

export const metadata: Metadata = { title: "Membership" };

async function readOnChainArt(tokenId: string | null) {
  if (!tokenId) return null;
  try {
    const uri = await getMembershipMetadata(tokenId);
    const payload = uri.split(",")[1];
    if (!payload) return null;
    const metadata = JSON.parse(Buffer.from(payload, "base64").toString("utf8")) as {
      image?: string;
    };
    return metadata.image ?? null;
  } catch {
    return null;
  }
}

export default async function MembershipPage() {
  const user = await requireRole("traveler");
  const db = readDb();
  const state = await getMemberChainState(user);
  const tier = getTier(state.tier);
  const progress = tierProgress(state.tier, state.lifetimeEarned);
  const art = await readOnChainArt(state.tokenId);

  return (
    <div className="mx-auto w-full max-w-[1240px] px-5 py-8 sm:px-8 lg:px-12 lg:py-11">
      <PageHeader
        eyebrow="Digital membership"
        title={`${tier.name} — ${tier.tagline.toLowerCase()}.`}
        description={tier.description}
        action={<ChainBadge connected={state.connected} />}
      />

      <div className="mt-8 grid gap-5 lg:grid-cols-[1.08fr_1fr]">
        <div className="space-y-4">
          <MembershipCard
            name={user.name}
            tier={state.tier}
            tokenId={state.tokenId}
            address={state.address}
            joinedAt={user.joinedAt}
          />

          {art ? (
            <div className="card p-4">
              <div className="mb-3 flex items-center justify-between gap-3 px-1">
                <p className="eyebrow text-muted">On-chain artwork</p>
                <span className="text-[9px] uppercase tracking-[0.12em] text-muted/60">
                  Generated by the contract
                </span>
              </div>
              <img
                src={art}
                alt="Voyara membership card rendered on-chain"
                className="w-full rounded-2xl border border-line/80"
              />
            </div>
          ) : null}
        </div>

        <div className="space-y-5">
          <section className="card card-padded">
            <div className="flex items-start justify-between gap-4">
              <div>
                <p className="eyebrow text-muted">Your tier</p>
                <h2 className="mt-2 font-display text-3xl text-forest">{tier.name}</h2>
              </div>
              <span
                className="rounded-full border px-3 py-1.5 text-[9px] font-semibold uppercase tracking-[0.14em]"
                style={{
                  borderColor: `${tier.accent}80`,
                  backgroundColor: `${tier.accent}1f`,
                  color: "#112a22",
                }}
              >
                Tier {tier.id}
              </span>
            </div>

            <div className="mt-5">
              <div className="flex items-center justify-between text-[10px] uppercase tracking-[0.12em] text-muted">
                <span>{formatNumber(state.lifetimeEarned)} VYA lifetime</span>
                <span>{progress.next ? `${progress.progress}%` : "Top tier"}</span>
              </div>
              <div className="mt-2 h-2 overflow-hidden rounded-full bg-parchment">
                <div
                  style={{ width: `${progress.progress}%` }}
                  className="h-full rounded-full bg-forest"
                />
              </div>
              <p className="mt-2.5 text-[11.5px] text-muted">
                {progress.next
                  ? `Earn ${formatNumber(progress.remaining)} more VYA to reach ${progress.next.name}.`
                  : "You have reached the highest Voyara tier."}
              </p>
            </div>

            <ul className="mt-5 space-y-2.5 border-t border-line/70 pt-5">
              {tier.benefits.map((benefit) => (
                <li key={benefit} className="flex items-start gap-2.5 text-[12px] text-ink/85">
                  <Sparkles className="mt-0.5 size-3.5 shrink-0 text-gold" />
                  {benefit}
                </li>
              ))}
            </ul>
          </section>

          <section className="card card-padded">
            <p className="eyebrow text-muted">Token details</p>
            <dl className="mt-4 space-y-3.5">
              <div className="flex items-center justify-between gap-4 border-b border-line/60 pb-3.5">
                <dt className="text-[11.5px] text-muted">Token ID</dt>
                <dd className="font-mono text-[11.5px] text-ink">
                  {state.tokenId ? `#${state.tokenId.padStart(4, "0")}` : "Not minted"}
                </dd>
              </div>
              <div className="flex items-center justify-between gap-4 border-b border-line/60 pb-3.5">
                <dt className="text-[11.5px] text-muted">Holder</dt>
                <dd className="flex items-center gap-2 font-mono text-[11px] text-ink">
                  {shortAddress(state.address, 6)}
                  <CopyButton value={state.address} className="text-muted/60" />
                </dd>
              </div>
              <div className="flex items-center justify-between gap-4 border-b border-line/60 pb-3.5">
                <dt className="text-[11.5px] text-muted">Contract</dt>
                <dd className="flex min-w-0 items-center gap-2 font-mono text-[10.5px] text-ink">
                  <span className="truncate">
                    {db.meta.membershipAddress ? shortAddress(db.meta.membershipAddress, 6) : "—"}
                  </span>
                  {db.meta.membershipAddress ? (
                    <CopyButton value={db.meta.membershipAddress} className="text-muted/60" />
                  ) : null}
                </dd>
              </div>
              <div className="flex items-center justify-between gap-4">
                <dt className="text-[11.5px] text-muted">Standard</dt>
                <dd className="text-[11.5px] text-ink">ERC-721 · soulbound</dd>
              </div>
            </dl>

            <div className="mt-4 flex flex-wrap items-center justify-between gap-3 border-t border-line/70 pt-4">
              <span className="flex items-center gap-1.5 text-[10px] text-muted">
                <ShieldCheck className="size-3.5 text-moss" />
                Non-transferable by design
              </span>
              {state.tokenId ? (
                <a
                  href={`/api/membership/${state.tokenId}`}
                  target="_blank"
                  rel="noreferrer"
                  className="link-line text-forest"
                >
                  Token metadata
                  <ExternalLink className="size-3.5" />
                </a>
              ) : null}
            </div>
          </section>
        </div>
      </div>

      <section className="mt-8">
        <div className="flex flex-wrap items-end justify-between gap-3">
          <div>
            <p className="eyebrow text-muted">The tiers</p>
            <h2 className="mt-2 font-display text-2xl text-forest">A membership that grows with you</h2>
          </div>
          <p className="text-[10.5px] text-muted/70">Lifetime VYA earned determines your tier.</p>
        </div>
        <div className="mt-4 grid gap-4 md:grid-cols-3">
          {TIERS.map((entry) => {
            const current = entry.id === state.tier;
            return (
              <article
                key={entry.id}
                className={
                  current
                    ? "rounded-[24px] border border-forest/30 bg-forest p-5 text-ivory"
                    : "rounded-[24px] border border-line/90 bg-cream p-5"
                }
              >
                <div className="flex items-center justify-between gap-3">
                  <p
                    className={
                      current
                        ? "eyebrow text-ivory/45"
                        : "eyebrow text-muted"
                    }
                  >
                    Tier {entry.id}
                  </p>
                  {current ? (
                    <span className="rounded-full bg-ivory/10 px-2.5 py-1 text-[8.5px] font-semibold uppercase tracking-[0.12em] text-gold">
                      Your tier
                    </span>
                  ) : null}
                </div>
                <h3
                  className={
                    current
                      ? "mt-3 font-display text-2xl text-ivory"
                      : "mt-3 font-display text-2xl text-forest"
                  }
                >
                  {entry.name}
                </h3>
                <p
                  className={
                    current
                      ? "mt-1 text-[10.5px] text-ivory/45"
                      : "mt-1 text-[10.5px] text-muted/70"
                  }
                >
                  {entry.threshold === 0
                    ? "From your first point"
                    : `${formatNumber(entry.threshold)} VYA lifetime`}
                </p>
                <ul className="mt-4 space-y-1.5">
                  {entry.benefits.slice(0, 4).map((benefit) => (
                    <li
                      key={benefit}
                      className={
                        current
                          ? "flex items-start gap-2 text-[11px] leading-5 text-ivory/70"
                          : "flex items-start gap-2 text-[11px] leading-5 text-muted"
                      }
                    >
                      <span
                        className="mt-1.5 size-1 shrink-0 rounded-full"
                        style={{ backgroundColor: entry.accent }}
                      />
                      {benefit}
                    </li>
                  ))}
                </ul>
              </article>
            );
          })}
        </div>
      </section>
    </div>
  );
}
