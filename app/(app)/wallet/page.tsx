import type { Metadata } from "next";
import { LockKeyhole } from "lucide-react";
import { ActivityLedger } from "@/components/app/activity-ledger";
import { BalancePanel } from "@/components/app/balance-panel";
import { ChainBadge } from "@/components/chain-badge";
import { CopyButton } from "@/components/app/copy-button";
import { PageHeader } from "@/components/app/page-header";
import { TransferForm } from "@/components/app/transfer-form";
import { requireRole } from "@/lib/auth";
import { getMemberChainState } from "@/lib/chain/read";
import { readDb } from "@/lib/db";
import { shortAddress } from "@/lib/format";

export const metadata: Metadata = { title: "Wallet" };

export default async function WalletPage() {
  const user = await requireRole("traveler");
  const db = readDb();
  const state = await getMemberChainState(user);

  const recipients = db.users
    .filter((entry) => entry.role === "traveler" && entry.status === "active" && entry.id !== user.id)
    .map((entry) => ({
      name: entry.name,
      address: entry.walletAddress,
      homeCity: entry.homeCity,
    }));

  const details = [
    { label: "Network", value: `Hardhat local · ${db.meta.chainId}` },
    { label: "Token contract", value: db.meta.tokenAddress ?? "Not deployed", copy: true },
    { label: "Membership contract", value: db.meta.membershipAddress ?? "Not deployed", copy: true },
    {
      label: "Membership token",
      value: state.tokenId ? `Voyara NFT #${state.tokenId.padStart(4, "0")}` : "Not minted",
    },
  ];

  return (
    <div className="mx-auto w-full max-w-[1240px] px-5 py-8 sm:px-8 lg:px-12 lg:py-11">
      <PageHeader
        eyebrow="Digital wallet"
        title="Points that move with you."
        description="Your VYA balance and membership live in a wallet on the local Voyara chain. Send points to another member or redeem them across the partner network."
        action={<ChainBadge connected={state.connected} />}
      />

      <div className="mt-8 grid gap-5 lg:grid-cols-[1.1fr_0.9fr]">
        <div className="space-y-5">
          <BalancePanel
            balance={state.balance}
            address={state.address}
            lifetimeEarned={state.lifetimeEarned}
            lifetimeRedeemed={state.lifetimeRedeemed}
            connected={state.connected}
            showActions={false}
          />

          <section className="card card-padded">
            <p className="eyebrow text-muted">Wallet details</p>
            <dl className="mt-4 space-y-3.5">
              <div className="flex items-center justify-between gap-4 border-b border-line/60 pb-3.5">
                <dt className="text-[11.5px] text-muted">Wallet address</dt>
                <dd className="flex items-center gap-2 text-[11.5px] font-medium text-ink">
                  <span className="font-mono">{shortAddress(state.address, 6)}</span>
                  <CopyButton value={state.address} className="text-muted/60" label="Copy" />
                </dd>
              </div>
              {details.map((detail) => (
                <div
                  key={detail.label}
                  className="flex items-center justify-between gap-4 border-b border-line/60 pb-3.5 last:border-0 last:pb-0"
                >
                  <dt className="shrink-0 text-[11.5px] text-muted">{detail.label}</dt>
                  <dd className="flex min-w-0 items-center gap-2 text-right text-[11.5px] font-medium text-ink">
                    <span className="truncate font-mono text-[10.5px]">{detail.value}</span>
                    {detail.copy ? (
                      <CopyButton value={detail.value} className="shrink-0 text-muted/60" label="Copy" />
                    ) : null}
                  </dd>
                </div>
              ))}
            </dl>
            <p className="mt-4 flex items-start gap-2 rounded-xl bg-parchment/50 px-3.5 py-3 text-[10.5px] leading-5 text-muted">
              <LockKeyhole className="mt-0.5 size-3.5 shrink-0 text-moss" />
              Demo custodial wallet. Keys are generated by the local deployment and never leave this
              machine.
            </p>
          </section>
        </div>

        <section className="card card-padded h-fit">
          <p className="eyebrow text-muted">Send points</p>
          <h2 className="mt-2 font-display text-2xl text-forest">A gift between members</h2>
          <p className="mt-2 text-[12px] leading-5 text-muted">
            Transfer VYA to any active Voyara member. The ERC-20 contract settles the movement in a
            single transaction.
          </p>
          <div className="mt-6">
            <TransferForm members={recipients} balance={state.balance} />
          </div>
        </section>
      </div>

      <section className="card mt-5 overflow-hidden">
        <div className="flex flex-wrap items-center justify-between gap-3 border-b border-line/70 px-5 py-4">
          <div>
            <p className="eyebrow text-muted">Activity ledger</p>
            <h2 className="mt-1.5 font-display text-xl text-forest">
              {state.activity.length} settled transactions
            </h2>
          </div>
          <span className="text-[10px] uppercase tracking-[0.12em] text-muted/70">
            Most recent first
          </span>
        </div>
        <ActivityLedger
          activity={state.activity}
          empty="No wallet activity yet. Earn with a partner to open your ledger."
        />
      </section>
    </div>
  );
}
